-- Categoría para registrar el dinero con el que el usuario empieza a usar la aplicación
INSERT INTO categoria (nombre, tipo) VALUES ('Saldo inicial', 'INGRESO');

-- Ingresos y gastos que se repiten cada mes (sueldo, alquiler, plan de celular...).
-- "dia" es el día del mes en que se registra (si el mes es más corto, se usa su último día).
-- "proximo_cargo" es la siguiente fecha que falta registrar: es el estado de la repetición, no un
-- dato derivado (si el usuario borra un movimiento generado, NO se vuelve a crear).
CREATE TABLE movimiento_recurrente (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    categoria_id   BIGINT        NOT NULL REFERENCES categoria (id),
    descripcion    VARCHAR(60)   NOT NULL,
    monto          NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    dia            INTEGER       NOT NULL CHECK (dia BETWEEN 1 AND 31),
    proximo_cargo  DATE          NOT NULL,
    activo         BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_recurrente_usuario ON movimiento_recurrente (usuario_id);

-- Cada movimiento generado automáticamente recuerda de qué repetición salió.
-- Si se elimina la repetición, los movimientos ya registrados se conservan.
ALTER TABLE movimiento
    ADD COLUMN recurrente_id BIGINT REFERENCES movimiento_recurrente (id) ON DELETE SET NULL;
