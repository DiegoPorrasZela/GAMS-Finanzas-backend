-- Esquema de GAMS Finanzas, normalizado hasta la Tercera Forma Normal (3FN):
--  1FN: todos los atributos son atómicos y cada tabla tiene clave primaria.
--  2FN: las claves primarias son simples (id), así que no hay dependencias parciales.
--  3FN: ningún atributo depende de otro que no sea la clave:
--       - el rol es una tabla aparte (usuario guarda solo rol_id, no el texto del rol);
--       - el tipo (INGRESO/GASTO) vive en categoria; movimiento NO lo repite, porque
--         dependería de categoria_id y no del id del movimiento (dependencia transitiva).

CREATE TABLE rol (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(80)  NOT NULL,
    email     VARCHAR(120) NOT NULL UNIQUE,
    password  VARCHAR(100) NOT NULL,  -- hash BCrypt, nunca la contraseña en texto plano
    rol_id    BIGINT       NOT NULL REFERENCES rol (id)
);

CREATE TABLE categoria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(50) NOT NULL,
    tipo    VARCHAR(10) NOT NULL CHECK (tipo IN ('INGRESO', 'GASTO')),
    CONSTRAINT uq_categoria_nombre_tipo UNIQUE (nombre, tipo)
);

CREATE TABLE movimiento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    categoria_id  BIGINT        NOT NULL REFERENCES categoria (id),
    descripcion   VARCHAR(60)   NOT NULL,
    monto         NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    fecha         DATE          NOT NULL
);

-- La consulta más frecuente: los movimientos de un usuario ordenados por fecha
CREATE INDEX idx_movimiento_usuario_fecha ON movimiento (usuario_id, fecha DESC);
