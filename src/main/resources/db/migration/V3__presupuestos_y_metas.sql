-- Planificación: presupuesto del mes y metas de ahorro (siguen en 3FN).
-- Los valores que se pueden calcular NO se guardan: lo gastado en el mes sale de "movimiento"
-- y lo ahorrado en una meta sale de sumar sus aportes. Así nunca hay datos contradictorios.

-- Plan de un usuario para un mes: cuánto quiere gastar como máximo y cuánto quiere ahorrar.
-- Clave candidata (usuario_id, anio, mes): cada usuario tiene un solo plan por mes.
CREATE TABLE presupuesto_mensual (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    anio             INTEGER       NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    mes              INTEGER       NOT NULL CHECK (mes BETWEEN 1 AND 12),
    limite_gasto     NUMERIC(12, 2) NOT NULL CHECK (limite_gasto > 0),
    ahorro_objetivo  NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (ahorro_objetivo >= 0),
    CONSTRAINT uq_presupuesto_usuario_mes UNIQUE (usuario_id, anio, mes)
);

-- Objetivo de ahorro (ej. "Laptop", S/ 2500 para junio). La fecha límite es opcional.
CREATE TABLE meta_ahorro (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT        NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    nombre          VARCHAR(60)   NOT NULL,
    monto_objetivo  NUMERIC(12, 2) NOT NULL CHECK (monto_objetivo > 0),
    fecha_limite    DATE
);

-- Cada vez que el usuario separa dinero para una meta
CREATE TABLE aporte (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meta_id  BIGINT        NOT NULL REFERENCES meta_ahorro (id) ON DELETE CASCADE,
    monto    NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    fecha    DATE          NOT NULL
);

CREATE INDEX idx_meta_ahorro_usuario ON meta_ahorro (usuario_id);
CREATE INDEX idx_aporte_meta ON aporte (meta_id);
